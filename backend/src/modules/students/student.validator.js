const Joi = require("joi");
const { validateSchema } = require("../../middleware/validation.middleware");

const createStudentSchema = Joi.object({
  userId: Joi.string().hex().length(24).required(),
  nameEnglish: Joi.string().trim().min(2).max(100).required(),
  nameArabic: Joi.string().trim().max(100).allow(""),
  placeEnglish: Joi.string().trim().max(100).allow(""),
  placeArabic: Joi.string().trim().max(100).allow(""),
  dateOfBirth: Joi.date().iso().required(),
  admissionYear: Joi.number().integer().min(2000).max(2100).required(),
  classId: Joi.string().hex().length(24).allow(null, ""),
  institutionId: Joi.string().hex().length(24).allow(null, ""),
  contactNumber: Joi.string().trim().allow(""),
  fatherName: Joi.string().trim().min(2).max(100).required(),
  motherName: Joi.string().trim().min(2).max(100).required(),
  photo: Joi.string().trim().allow(""),
  biometricId: Joi.string().trim().allow("", null).optional(),
  house: Joi.string().valid("RED", "BLUE", "GREEN", "YELLOW").allow("", null).optional(),
  mentorId: Joi.string().hex().length(24).allow(null, "").optional(),
  disciplineScore: Joi.number().min(0).max(100).optional(),
  skills: Joi.object({
    quran: Joi.number().min(0).max(100),
    arabic: Joi.number().min(0).max(100),
    english: Joi.number().min(0).max(100),
    urdu: Joi.number().min(0).max(100),
    communication: Joi.number().min(0).max(100),
    leadership: Joi.number().min(0).max(100),
  }).optional(),
  parentUserId: Joi.string().hex().length(24).allow(null, "").optional(),
  parentName: Joi.string().trim().min(2).max(100).allow("", null).optional(),
  parentEmail: Joi.string().email().lowercase().trim().allow("", null).optional(),
  parentMobile: Joi.string().trim().allow("", null).optional(),
  relationship: Joi.string().valid("FATHER", "MOTHER", "GUARDIAN").allow("", null).optional(),
  relationType: Joi.string().valid("FATHER", "MOTHER", "GUARDIAN").allow("", null).optional(),
});

